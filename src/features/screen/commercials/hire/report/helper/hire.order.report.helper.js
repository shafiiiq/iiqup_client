const BG_STYLE_KEYS = ['background', 'backgroundImage', 'backgroundSize', 'backgroundRepeat', 'backgroundPosition', 'backgroundAttachment'];
const PAPER_WIDTH_MM = 297;
const PAPER_HEIGHT_MM = 420;

