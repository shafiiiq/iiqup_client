export const buildTimestamp = () => {
  const date = new Date();
  const d = date.toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' });
  const t = date.toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit', hour12: true });
  return `This document was generated by the system on ${d}, at ${t}.`;
};

const waitForImages = (element) => {
  const images = Array.from(element.querySelectorAll('img'));
  return Promise.all(images.map((img) => {
    if (img.complete && img.naturalHeight !== 0) return Promise.resolve();
    return new Promise((resolve) => {
      img.addEventListener('load', resolve, { once: true });
      img.addEventListener('error', resolve, { once: true });
    });
  }));
};

const nextFrame = () => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve)));

const KERNING_FIX_ID = 'html2canvas-kerning-fix-hire-order';

const injectKerningFix = () => {
  const style = document.createElement('style');
  style.id = KERNING_FIX_ID;
  style.textContent = `
    .a2-paper, .a2-paper * {
      font-kerning: none !important;
      font-variant-ligatures: none !important;
      -webkit-font-feature-settings: "liga" 0, "kern" 0 !important;
      font-feature-settings: "liga" 0, "kern" 0 !important;
      letter-spacing: normal !important;
      text-rendering: geometricPrecision !important;
    }
  `;
  document.head.appendChild(style);
  return style;
};

const removeKerningFix = (style) => {
  if (style && style.parentNode) style.parentNode.removeChild(style);
};

export const captureElementToCanvas = async (element) => {
  const rootOriginal = {};
  BG_STYLE_KEYS.forEach((key) => { rootOriginal[key] = element.style[key]; });
  Object.assign(element.style, {
    background: '#FFFFFF',
    backgroundImage: 'none',
    backgroundSize: 'auto',
    backgroundRepeat: 'no-repeat',
    backgroundPosition: 'initial',
    backgroundAttachment: 'initial',
  });

  const children = element.querySelectorAll('*');
  const childOriginals = [];
  children.forEach((child, idx) => {
    childOriginals[idx] = {};
    BG_STYLE_KEYS.forEach((key) => { childOriginals[idx][key] = child.style[key]; });
    if (child.style.backgroundImage && /grid|linear-gradient|repeating/.test(child.style.backgroundImage)) {
      child.style.backgroundImage = 'none';
    }
  });

  const kerningStyle = injectKerningFix();

  await document.fonts.ready;
  await waitForImages(element);
  await nextFrame();

  let canvas;
  try {
    canvas = await html2canvas(element, {
      scale: 2,
      logging: false,
      useCORS: true,
      allowTaint: false,
      scrollX: 0,
      scrollY: 0,
      windowWidth: element.scrollWidth,
      windowHeight: element.scrollHeight,
      backgroundColor: '#FFFFFF',
      foreignObjectRendering: false,
      letterRendering: true,
      ignoreElements: (el) => {
        const cs = window.getComputedStyle(el);
        return cs.backgroundImage && /grid|repeating/.test(cs.backgroundImage);
      },
      removeContainer: true,
    });
  } finally {
    removeKerningFix(kerningStyle);
    Object.assign(element.style, rootOriginal);
    children.forEach((child, idx) => Object.assign(child.style, childOriginals[idx]));
  }

  return canvas;
};

export const buildPdf = async () => {
  const pdf = new jsPDF({ orientation: 'portrait', unit: 'mm', format: [PAPER_WIDTH_MM, PAPER_HEIGHT_MM] });
  const allDocuments = document.querySelectorAll('.a2-paper');
  await document.fonts.ready;

  for (let i = 0; i < allDocuments.length; i++) {
    const canvas = await captureElementToCanvas(allDocuments[i]);
    const imgData = canvas.toDataURL('image/png', 1.0);
    const imgHeight = (canvas.height * PAPER_WIDTH_MM) / canvas.width;

    if (i > 0) pdf.addPage([PAPER_WIDTH_MM, PAPER_HEIGHT_MM], 'portrait');
    pdf.addImage(imgData, 'PNG', 0, 0, PAPER_WIDTH_MM, imgHeight);
  }

  return pdf;
};

